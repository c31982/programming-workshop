package com.doveoverlamb.sesion15;

public class Ejercicio01 {

    /*
        Ejercicio 1. Contador ascendente
        
        Mostrar los números del 1 al 10.
     */
    public static void main(String args[]) {
        for (int i = 1; i <= 10; i++) {
            System.out.print(i + " ");
        }

    }
}
