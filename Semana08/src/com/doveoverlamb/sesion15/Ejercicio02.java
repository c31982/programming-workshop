package com.doveoverlamb.sesion15;

public class Ejercicio02 {

    /*
        Ejercicio 2. Contador descendente
        Mostrar los números del 10 al 1.

     */
    public static void main(String args[]) {
        for (int i = 10; i >= 1; i--) {
            System.out.print(i + " ");
        }

    }
}
