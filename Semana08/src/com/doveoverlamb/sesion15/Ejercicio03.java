package com.doveoverlamb.sesion15;

public class Ejercicio03 {

    /*
        Ejercicio 3. Números pares
    
        Mostrar los pares del 2 al 20 de dos maneras.
     */
    public static void main(String args[]) {
        for (int i = 2; i <= 20; i++) {
            if (i % 2 == 0) {
                System.out.println(i + " ");
            }
        }
    }
}
